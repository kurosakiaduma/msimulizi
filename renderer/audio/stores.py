class AzureBlobStore:
    """
    Azure Blob Storage implementation of AudioStore.

    The supplied container client must support asynchronous methods such as
    get_blob_client(), get_blob_properties(), upload_blob(), and close().

    Authentication:
        Use a managed identity in Azure production. Grant it the appropriate
        Blob data-plane role, such as Storage Blob Data Contributor, scoped
        to the intended storage account or container.

    Playback:
        By default, this store returns the SDK blob URL. A browser needs a
        URL it can access. That can be:
        - A blob in a deliberately public-read container.
        - A stable, authenticated application endpoint.
        - A URL generated through a custom url_resolver.

    This class does not change the container's public access setting.
    """

    def __init__(
        self,
        container_client: Any,
        credential: Any | None = None,
        *,
        cache_control: str = DEFAULT_CACHE_CONTROL,
        url_resolver: UrlResolver | None = None,
        close_container_client: bool = True,
    ) -> None:
        if container_client is None:
            raise ValueError("container_client is required")

        self._container = container_client
        self._credential = credential
        self._cache_control = cache_control
        self._url_resolver = url_resolver
        self._close_container_client = close_container_client

    @classmethod
    def from_account(
        cls,
        account_url: str,
        container: str = "audio",
        *,
        cache_control: str = DEFAULT_CACHE_CONTROL,
        url_resolver: UrlResolver | None = None,
    ) -> "AzureBlobStore":
        """
        Create an asynchronous Azure Blob container client.

        Example:
            AzureBlobStore.from_account(
                "https://example.blob.core.windows.net",
                container="audio",
            )

        DefaultAzureCredential supports managed identity in Azure and approved
        developer credentials locally. No account key is hard-coded here.

        Requires:
            pip install azure-identity azure-storage-blob
        """
        if not account_url or not account_url.strip():
            raise ValueError("Azure Blob account URL is required")

        if not container or not container.strip():
            raise ValueError("Azure Blob container name is required")

        try:
            from azure.identity.aio import DefaultAzureCredential
            from azure.storage.blob.aio import ContainerClient
        except ImportError as exc:
            raise RuntimeError(
                "Azure Blob dependencies are missing. Install "
                "'azure-identity' and 'azure-storage-blob'."
            ) from exc

        credential = DefaultAzureCredential()

        try:
            container_client = ContainerClient(
                account_url=account_url.rstrip("/"),
                container_name=container,
                credential=credential,
            )
        except Exception:
            # Avoid silently swallowing construction errors. The credentials
            # object is closed when the returned store is closed; if client
            # construction fails, callers should see the original exception.
            raise

        return cls(
            container_client,
            credential,
            cache_control=cache_control,
            url_resolver=url_resolver,
        )

    @staticmethod
    def _blob_name(
        key: str,
        ext: str,
    ) -> str:
        """Build a validated Azure blob name from the extension-free key."""
        return f"{_normalise_key(key)}.{_normalise_ext(ext)}"

    async def _resolve_url(
        self,
        blob_name: str,
        default_blob_url: str,
    ) -> str:
        """
        Resolve the playback URL for the frontend.

        A custom resolver may be synchronous or asynchronous. For production
        private storage, a stable API URL is preferable when returned URLs are
        held in AudioService's in-memory memo cache.
        """
        if self._url_resolver is None:
            result = default_blob_url
        else:
            result = await _maybe_await(
                self._url_resolver(blob_name, default_blob_url)
            )

        if not isinstance(result, str) or not result.strip():
            raise RuntimeError(
                f"No playable audio URL resolved for blob {blob_name!r}"
            )

        return result

    async def get(
        self,
        key: str,
        ext: str = "mp3",
    ) -> StoredAudio | None:
        """
        Return an existing blob's playback URL and duration metadata.

        A 404/missing blob returns None. Authentication, permission, network
        and other Azure failures are not misrepresented as cache misses.
        """
        blob_name = self._blob_name(key, ext)
        blob = self._container.get_blob_client(blob_name)

        try:
            properties = await blob.get_blob_properties()
        except Exception as exc:
            # Import lazily so importing the local-only store does not require
            # the Azure SDK to be installed.
            try:
                from azure.core.exceptions import ResourceNotFoundError
            except ImportError:
                ResourceNotFoundError = ()  # type: ignore[assignment,misc]

            status_code = getattr(exc, "status_code", None)

            if (
                isinstance(exc, ResourceNotFoundError)
                or status_code == 404
                or type(exc).__name__ == "ResourceNotFoundError"
            ):
                return None

            raise

        metadata = getattr(properties, "metadata", None) or {}
        duration = _duration_from_metadata(metadata)

        default_url = getattr(blob, "url", None)
        if not default_url:
            raise RuntimeError(
                f"Azure Blob client did not expose a URL for {blob_name!r}"
            )

        url = await self._resolve_url(blob_name, default_url)

        return StoredAudio(
            url=url,
            duration_ms=duration,
        )

    async def put(
        self,
        key: str,
        data: bytes,
        duration_ms: int | None,
        ext: str = "mp3",
    ) -> StoredAudio:
        """
        Upload audio with the correct Content-Type and cache-control headers.

        Content-addressed keys are immutable by convention. `overwrite=True`
        makes concurrent writes of the same cached object harmless.

        Azure Blob metadata is stored as strings for interoperability.
        """
        if not isinstance(data, bytes):
            raise TypeError("Audio data must be bytes")

        duration = _normalise_duration(duration_ms)
        normalized_ext = _normalise_ext(ext)
        blob_name = self._blob_name(key, normalized_ext)

        # Keep imports local so development code importing LocalDirStore does
        # not require Azure packages to be present.
        try:
            from azure.storage.blob import ContentSettings
        except ImportError as exc:
            raise RuntimeError(
                "Azure Blob dependencies are missing. Install "
                "'azure-storage-blob'."
            ) from exc

        blob = self._container.get_blob_client(blob_name)

        metadata = _metadata_for_audio(
            data=data,
            duration_ms=duration,
            ext=normalized_ext,
            cache_control=self._cache_control,
        )

        content_settings = ContentSettings(
            content_type=_content_type(normalized_ext),
            cache_control=self._cache_control,
        )

        await blob.upload_blob(
            data,
            overwrite=True,
            content_settings=content_settings,
            metadata=metadata,
        )

        default_url = getattr(blob, "url", None)
        if not default_url:
            raise RuntimeError(
                f"Azure Blob client did not expose a URL for {blob_name!r}"
            )

        url = await self._resolve_url(blob_name, default_url)

        return StoredAudio(
            url=url,
            duration_ms=duration,
        )

    async def aclose(self) -> None:
        """Close the owned Azure container client and async credential."""
        errors: list[Exception] = []

        if self._close_container_client:
            close = getattr(self._container, "close", None)
            if callable(close):
                try:
                    await _maybe_await(close())
                except Exception as exc:
                    errors.append(exc)

        if self._credential is not None:
            close = getattr(self._credential, "close", None)
            if callable(close):
                try:
                    await _maybe_await(close())
                except Exception as exc:
                    errors.append(exc)

        if errors:
            logger.warning(
                "One or more Azure Blob resources failed to close: %s",
                "; ".join(str(error) for error in errors),
            )


