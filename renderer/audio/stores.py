# LocalDirStore
# ===========================================================================

class LocalDirStore:
    """
    Local filesystem implementation of AudioStore.

    Suitable for:
    - Local development
    - Unit and integration tests
    - Offline experiments

    Do not rely on a container's local filesystem for durable production
    storage unless it is backed by a deliberately configured persistent volume.
    """

    def __init__(
        self,
        directory: str | Path = ".audio_cache",
        *,
        cache_control: str = DEFAULT_CACHE_CONTROL,
    ) -> None:
        self.dir = Path(directory).expanduser().resolve()
        self.dir.mkdir(parents=True, exist_ok=True)
        self.cache_control = cache_control

    def _paths(
        self,
        key: str,
        ext: str,
    ) -> tuple[Path, Path]:
        """Resolve validated key and extension into audio and metadata paths."""
        safe_key = _normalise_key(key)
        safe_ext = _normalise_ext(ext)

        components = safe_key.split("/")
        parent = self.dir.joinpath(*components[:-1])

        audio_path = parent / f"{components[-1]}.{safe_ext}"
        metadata_path = parent / f"{components[-1]}.{safe_ext}.json"

        # Defence in depth: ensure resolved paths remain beneath the store.
        root = self.dir.resolve()
        if (
            not audio_path.resolve().is_relative_to(root)
            or not metadata_path.resolve().is_relative_to(root)
        ):
            raise ValueError("Resolved audio path escapes the storage directory")

        return audio_path, metadata_path

    async def get(
        self,
        key: str,
        ext: str = "mp3",
    ) -> StoredAudio | None:
        """
        Return the existing audio location and duration, or None on a cache miss.

        Both the audio file and sidecar must exist. Corrupt or incomplete
        metadata is treated as a cache miss rather than a successful hit.
        """
        return await asyncio.to_thread(self._get_sync, key, ext)

    def _get_sync(
        self,
        key: str,
        ext: str,
    ) -> StoredAudio | None:
        audio_path, metadata_path = self._paths(key, ext)

        if not audio_path.is_file() or not metadata_path.is_file():
            return None

        try:
            metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, json.JSONDecodeError):
            logger.warning(
                "Audio cache metadata is missing or invalid: %s",
                metadata_path,
            )
            return None

        if not isinstance(metadata, dict):
            return None

        # Read only the sidecar here: AudioService needs the location and
        # duration, not the full audio bytes.
        return StoredAudio(
            url=str(audio_path),
            duration_ms=_duration_from_metadata(metadata),
        )

    async def put(
        self,
        key: str,
        data: bytes,
        duration_ms: int | None,
        ext: str = "mp3",
    ) -> StoredAudio:
        """Atomically save audio and its JSON metadata sidecar."""
        return await asyncio.to_thread(
            self._put_sync,
            key,
            data,
            duration_ms,
            ext,
        )

    def _put_sync(
        self,
        key: str,
        data: bytes,
        duration_ms: int | None,
        ext: str,
    ) -> StoredAudio:
        if not isinstance(data, bytes):
            raise TypeError("Audio data must be bytes")

        duration = _normalise_duration(duration_ms)
        audio_path, metadata_path = self._paths(key, ext)
        normalized_ext = _normalise_ext(ext)

        metadata = _metadata_for_audio(
            data=data,
            duration_ms=duration,
            ext=normalized_ext,
            cache_control=self.cache_control,
        )

        # The object key is content-addressed, so replacing the same key
        # is expected to replace identical cached output. Each file is
        # atomically replaced. The sidecar is written last so readers do not
        # treat newly written audio without metadata as a complete entry.
        _atomic_write(audio_path, data)
        _atomic_write(metadata_path, _metadata_json(metadata))

        return StoredAudio(
            url=str(audio_path),
            duration_ms=duration,
        )

    async def aclose(self) -> None:
        """No persistent client resources need to be closed."""
        return None


