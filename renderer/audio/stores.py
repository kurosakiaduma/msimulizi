
"""
Audio storage backends for Msimulizi.

Production:
    AzureBlobStore
        Stores content-addressed audio in Azure Blob Storage.

Development/testing:
    LocalDirStore
        Stores audio on the local filesystem with JSON sidecar metadata.

Both implement the AudioStore protocol in contract.py.

Stored objects:
    <key>.<ext>        The audio file/blob
    <key>.<ext>.json   Local metadata sidecar only

The key is an extension-free object key generated by AudioService.
It may contain safe virtual-directory separators, for example:
    a1b2c3...
    audio/sw/a1b2c3...

The extension is supplied separately, for example "mp3" or "wav".
"""

from __future__ import annotations

import asyncio
import hashlib
import inspect
import json
import logging
import os
import re
import tempfile

from pathlib import Path
from typing import Any, Awaitable, Callable

from .contract import StoredAudio


logger = logging.getLogger("msimulizi.audio.storage")


# ===========================================================================
# Shared helpers
# ===========================================================================

METADATA_VERSION = 1

# These defaults are appropriate for immutable, content-addressed audio that
# is intentionally publicly accessible. Override this value for other access
# and privacy policies.
DEFAULT_CACHE_CONTROL = "public, max-age=31536000, immutable"

# Correct HTTP Content-Type values for supported audio formats.
CONTENT_TYPES: dict[str, str] = {
    "mp3": "audio/mpeg",
    "mpeg": "audio/mpeg",
    "wav": "audio/wav",
    "ogg": "audio/ogg",
    "oga": "audio/ogg",
    "opus": "audio/opus",
    "m4a": "audio/mp4",
    "mp4": "audio/mp4",
    "aac": "audio/aac",
    "flac": "audio/flac",
    "webm": "audio/webm",
}

_EXT_RE = re.compile(r"^[a-z0-9]{1,10}$")


# Optional custom URL resolver. It receives the complete blob name and the
# Azure SDK's default blob URL. It may return a stable playable URL, such as
# an application audio endpoint. Sync and async callbacks are both supported.
UrlResolver = Callable[
    [str, str],
    str | Awaitable[str],
]


async def _maybe_await(value: Any) -> Any:
    """Await values returned by asynchronous clients or callbacks."""
    if inspect.isawaitable(value):
        return await value
    return value


def _normalise_key(key: str) -> str:
    """
    Validate and normalize an extension-free storage key.

    Nested keys are allowed. Absolute paths, empty path components and parent
    traversal are rejected to prevent filesystem path traversal and malformed
    blob names.
    """
    if not isinstance(key, str):
        raise TypeError("Audio storage key must be a string")

    value = key.strip().replace("\\", "/")

    if not value:
        raise ValueError("Audio storage key cannot be empty")

    if value.startswith("/"):
        raise ValueError("Audio storage key cannot be an absolute path")

    if "\x00" in value:
        raise ValueError("Audio storage key cannot contain a null byte")

    parts = value.split("/")

    if any(part in ("", ".", "..") for part in parts):
        raise ValueError(
            "Audio storage key contains an invalid path component"
        )

    return "/".join(parts)


def _normalise_ext(ext: str) -> str:
    """Normalize an extension such as '.MP3' to 'mp3'."""
    if not isinstance(ext, str):
        raise TypeError("Audio extension must be a string")

    value = ext.strip().lower().lstrip(".")

    if not _EXT_RE.fullmatch(value):
        raise ValueError(f"Invalid audio extension: {ext!r}")

    return value


def _content_type(ext: str) -> str:
    """Return the MIME type matching the audio file extension."""
    return CONTENT_TYPES.get(
        _normalise_ext(ext),
        "application/octet-stream",
    )


def _normalise_duration(duration_ms: int | None) -> int | None:
    """Validate and normalize the optional audio duration."""
    if duration_ms is None:
        return None

    if isinstance(duration_ms, bool):
        raise ValueError("duration_ms must be a non-negative integer or None")

    duration = int(duration_ms)

    if duration < 0:
        raise ValueError("duration_ms cannot be negative")

    return duration


def _duration_from_metadata(metadata: dict[str, Any] | None) -> int | None:
    """Read duration_ms from storage metadata without trusting its contents."""
    if not metadata:
        return None

    normalized = {
        str(key).lower(): value
        for key, value in metadata.items()
    }

    value = normalized.get("duration_ms")

    if value is None:
        return None

    try:
        duration = int(value)
    except (TypeError, ValueError):
        return None

    return duration if duration >= 0 else None


def _metadata_for_audio(
    *,
    data: bytes,
    duration_ms: int | None,
    ext: str,
    cache_control: str,
) -> dict[str, str]:
    """
    Build string-only metadata for both local and Azure storage.

    Azure Blob metadata values are strings. Local sidecars use the same
    representation for consistency.
    """
    metadata = {
        "metadata_version": str(METADATA_VERSION),
        "audio_ext": ext,
        "content_type": _content_type(ext),
        "cache_control": cache_control,
        "sha256": hashlib.sha256(data).hexdigest(),
        "byte_length": str(len(data)),
    }

    if duration_ms is not None:
        metadata["duration_ms"] = str(duration_ms)

    return metadata


def _atomic_write(path: Path, data: bytes) -> None:
    """
    Atomically replace a local file.

    The temporary file is created in the destination directory so that
    os.replace() stays on the same filesystem.
    """
    path.parent.mkdir(parents=True, exist_ok=True)

    fd, temporary_name = tempfile.mkstemp(
        prefix=f".{path.name}.",
        suffix=".tmp",
        dir=path.parent,
    )
    temporary_path = Path(temporary_name)

    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())

        os.replace(temporary_path, path)

    except BaseException:
        try:
            temporary_path.unlink(missing_ok=True)
        except OSError:
            pass
        raise


def _metadata_json(metadata: dict[str, Any]) -> bytes:
    """Serialize metadata to UTF-8 JSON with a stable representation."""
    return json.dumps(
        metadata,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")


