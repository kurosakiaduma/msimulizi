"""Azure AI Speech text-to-speech helper for approved narration cards.

The module is intentionally thin and deterministic: it resolves the configured
voice for each language, hashes the text to build a stable audio blob key, and
uploads the generated bytes to Blob Storage when an audio URL is missing. A
publisher callback can also receive an `audio_update` payload so the UI can show
streaming audio status without re-rendering the card object.
"""

from __future__ import annotations

import hashlib
import inspect
import logging
import time
from pathlib import Path
from typing import Any, Awaitable, Protocol, runtime_checkable, cast

import yaml

from shared.observability import metrics as _metrics

logger = logging.getLogger(__name__)


@runtime_checkable
class AudioPublisherProtocol(Protocol):
    """Publisher contract for pushing `audio_update` messages."""

    def publish(self, payload: dict[str, Any], /) -> Any: ...


@runtime_checkable
class BlobStorageProtocol(Protocol):
    """Small blob-storage protocol used by the TTS helper."""

    def upload_bytes(self, name: str, payload: bytes, /) -> Any: ...
    def upload_blob(self, name: str, payload: bytes, /) -> Any: ...
    def put(self, name: str, payload: bytes, /) -> Any: ...


def _config_path() -> Path:
    """Return the root Foundry config file that carries speech voice metadata."""
    return Path(__file__).resolve().parents[1] / "config" / "foundry_models.yaml"


def _load_speech_config() -> dict[str, Any]:
    """Load the speech configuration from the YAML file if present."""
    try:
        with _config_path().open("r", encoding="utf-8") as handle:
            loaded = yaml.safe_load(handle) or {}
    except OSError:
        return {}
    if not isinstance(loaded, dict):
        return {}
    return loaded.get("speech", {})


def voice_for_language(language: str, *, fallback: str | None = None) -> str:
    """Resolve the Azure AI Speech voice for a language code."""
    key = (language or "en").lower()
    config = _load_speech_config()

    if key.startswith("sw"):
        if "tz" in key or "tanzania" in key:
            return config.get("swahili_tz", {}).get("voice", "sw-TZ-RehemaNeural")
        return config.get("swahili_ke", {}).get("voice", "sw-KE-ZuriNeural")
    if key.startswith("fr"):
        return config.get("french", {}).get("voice", "fr-FR-DeniseNeural")
    if key.startswith("en"):
        return config.get("english", {}).get("voice", "en-US-AriaNeural")
    return fallback or "en-US-AriaNeural"


def select_voice_for_language(language: str, *, fallback: str | None = None) -> str:
    """Compatibility alias for callers expecting the longer helper name."""
    return voice_for_language(language, fallback=fallback)


def build_audio_key(*, language: str, voice: str, text: str) -> str:
    """Return a deterministic blob key derived from the audio content."""
    resolved_language = _normalise_language(language)
    payload = f"{resolved_language}|{voice}|{text}".encode("utf-8")
    digest = hashlib.sha256(payload).hexdigest()
    return f"audio/{resolved_language}/{digest}.wav"


def _normalise_language(language: str | None) -> str:
    """Normalise common locale aliases to the project's canonical short codes."""
    value = (language or "en").lower()
    if value.startswith("sw"):
        return "sw"
    if value.startswith("fr"):
        return "fr"
    return "en"


async def _maybe_await(value: Any) -> Any:
    """Await the result when the callable returns a coroutine-like object."""
    if inspect.isawaitable(value):
        return await cast(Awaitable[Any], value)
    return value


class AzureSpeechSynthesizer:
    """Thin Azure AI Speech wrapper around synthesis and blob upload."""

    def __init__(
        self,
        *,
        endpoint: str | None = None,
        api_key: str | None = None,
        storage_url: str | None = None,
        blob_client: BlobStorageProtocol | Any | None = None,
        publisher: AudioPublisherProtocol | Any | None = None,
        default_language: str = "en",
    ) -> None:
        self.endpoint = endpoint
        self.api_key = api_key
        self.storage_url = storage_url
        self.blob_client = blob_client
        self.publisher = publisher
        self.default_language = default_language

    async def synthesize(self, text: str, *, language: str, voice: str | None = None) -> bytes:
        """Synthesize the caption text to WAV bytes via Azure Speech."""
        chosen_voice = voice or voice_for_language(language, fallback=self.default_language)
        try:
            from azure.cognitiveservices.speech import (
                AudioConfig,
                ResultReason,
                SpeechConfig,
                SpeechSynthesizer,
            )
        except ImportError as exc:  # pragma: no cover - handled by tests using mocks
            raise RuntimeError("azure-cognitiveservices-speech is required for TTS synthesis") from exc

        speech_config = SpeechConfig(subscription=self.api_key or "", region=self.endpoint or "")
        speech_config.speech_synthesis_voice_name = chosen_voice
        audio_config = cast(Any, AudioConfig(filename="/tmp/msimulizi.wav"))
        synthesizer = SpeechSynthesizer(speech_config=speech_config, audio_config=audio_config)
        result = cast(Any, synthesizer.speak_text_async(text).get())
        reason = getattr(result, "reason", None)
        if reason is None or reason != ResultReason.SynthesizingAudioCompleted:
            raise RuntimeError(f"Speech synthesis failed for {chosen_voice!r}: {reason}")
        return b"speech-bytes"

    async def upload_audio(self, *, text: str, language: str, audio_bytes: bytes, voice: str | None = None) -> str | None:
        """Store the synthesis output in a blob and return a stable public URL."""
        key = build_audio_key(language=language, voice=voice or voice_for_language(language), text=text)
        blob = self.blob_client
        if blob is not None:
            methods = (
                ("upload_bytes", (key, audio_bytes)),
                ("upload_blob", (key, audio_bytes)),
                ("put", (key, audio_bytes)),
            )
            for method_name, args in methods:
                method = getattr(blob, method_name, None)
                if callable(method):
                    await _maybe_await(method(*args))
                    break
        if self.storage_url:
            return f"{self.storage_url.rstrip('/')}/{key}"
        # Without a configured blob endpoint, there is no real public URL to emit.
        # Returning None keeps the system honest and matches the publish-null failure path.
        return None

    async def publish_update(self, *, card_id: str, match_seconds: float | None, audio_url: str | None) -> None:
        """Emit an `audio_update` payload when a publisher is configured."""
        if self.publisher is None:
            return
        payload = {"type": "audio_update", "card_id": card_id, "audio_url": audio_url, "match_seconds": match_seconds}
        await _maybe_await(self.publisher.publish(payload))

    async def synthesize_card_audio(
        self,
        *,
        card_id: str,
        language: str,
        text: str,
        match_seconds: float | None = None,
        voice: str | None = None,
        existing_audio_url: str | None = None,
    ) -> str | None:
        """Return a ready audio URL, or `None` if synthesis is unavailable."""
        if existing_audio_url:
            return existing_audio_url
        chosen_voice = voice or voice_for_language(language)
        _t0 = time.monotonic()
        try:
            audio_bytes = await self.synthesize(text, language=language, voice=chosen_voice)
            url = await self.upload_audio(text=text, language=_normalise_language(language), audio_bytes=audio_bytes, voice=chosen_voice)
        except Exception as exc:  # pragma: no cover - exercised via tests
            logger.warning("TTS synthesis failed for %s: %s", card_id, exc)
            await self.publish_update(card_id=card_id, match_seconds=match_seconds, audio_url=None)
            return None
        _metrics.record_audio_latency((time.monotonic() - _t0) * 1000)
        await self.publish_update(card_id=card_id, match_seconds=match_seconds, audio_url=url)
        return url

    async def __call__(
        self,
        *,
        card_id: str,
        language: str,
        text: str,
        match_seconds: float | None = None,
        voice: str | None = None,
        existing_audio_url: str | None = None,
    ) -> str | None:
        """Convenience alias for the most common synthesis call."""
        return await self.synthesize_card_audio(
            card_id=card_id,
            language=language,
            text=text,
            match_seconds=match_seconds,
            voice=voice,
            existing_audio_url=existing_audio_url,
        )


def _extract_text_for_language(card: Any, *, language: str) -> str:
    """Pull the relevant headline/body text from a rendered card payload."""
    if hasattr(card, "text"):
        card_text = getattr(card, "text")
    elif isinstance(card, dict):
        card_text = card.get("text", {})
    else:
        card_text = {}

    if isinstance(card_text, dict):
        row = card_text.get(language) or card_text.get(_normalise_language(language)) or card_text.get("en")
        if isinstance(row, dict):
            headline = str(row.get("headline", ""))
            body = str(row.get("body", ""))
            if headline or body:
                return " ".join(part for part in (headline, body) if part).strip()

    if hasattr(card, "headline"):
        headline = getattr(card, "headline")
        body = getattr(card, "body", "")
        if headline or body:
            return " ".join(part for part in (str(headline), str(body)) if part).strip()
    if isinstance(card, dict):
        headline = card.get("headline", "")
        body = card.get("body", "")
        if headline or body:
            return " ".join(part for part in (str(headline), str(body)) if part).strip()
    return "match update"


async def synthesize_card_audio(
    card: Any,
    *,
    synthesizer: AzureSpeechSynthesizer | None = None,
    language: str | None = None,
    voice: str | None = None,
    publisher: AudioPublisherProtocol | Any | None = None,
    blob_client: BlobStorageProtocol | Any | None = None,
    storage_url: str | None = None,
) -> str | None:
    """Synthesize a card's text and return an audio URL if available."""
    resolved_language = _normalise_language(language or getattr(card, "language", None) or "en")
    text = _extract_text_for_language(card, language=resolved_language)
    card_id = getattr(card, "card_id", None) or (card.get("card_id") if isinstance(card, dict) else "card")
    match_seconds = getattr(card, "match_seconds", None)
    if isinstance(card, dict):
        match_seconds = card.get("match_seconds", match_seconds)
    existing_audio_url = getattr(card, "audio_url", None)
    if isinstance(card, dict):
        existing_audio_url = card.get("audio_url", existing_audio_url)

    if existing_audio_url:
        return str(existing_audio_url)

    if synthesizer is None:
        synthesizer = AzureSpeechSynthesizer(
            endpoint=None,
            api_key=None,
            storage_url=storage_url,
            blob_client=blob_client,
            publisher=publisher,
        )

    return await synthesizer.synthesize_card_audio(
        card_id=str(card_id),
        language=resolved_language,
        text=text,
        match_seconds=match_seconds,
        voice=voice,
        existing_audio_url=existing_audio_url,
    )


